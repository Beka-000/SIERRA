// ─── Тип переводов ────────────────────────────────────────────────────────────

export type Translations = typeof translations.ru;

// ─── Хелпер ──────────────────────────────────────────────────────────────────

export function t(locale: Locale = DEFAULT_LOCALE): Translations {
  return (translations[locale] ?? translations[DEFAULT_LOCALE]) as unknown as Translations;
}

// ─── Определение локали из Accept-Language ────────────────────────────────────

export function detectLocale(acceptLanguage?: string): Locale {
  if (!acceptLanguage) return DEFAULT_LOCALE;
  const lang = acceptLanguage.split(",")[0].split("-")[0].toLowerCase();
  if (lang === "ky" || lang === "kg") return "ky";
  if (lang === "en") return "en";
  return "ru";
}
